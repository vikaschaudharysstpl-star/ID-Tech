bool parser_feed(uint8_t byte, Packet *packet)
{
	static STMType StateMachine;
	uint8_t checksum=0;
	switch(StateMachine)
	{
		case ST_Wait:			// wait until 16 bytes are received to chalculate the checksum
		{
			uint8_t received_byte = Rxbuff.Head - Rxbuff.tail;

			if (received_byte >= 16)		// check 16 are received
			{
				if ((Rxbuff.data[Rxbuff.tail] == STARTBYTE) && (Rxbuff.data[Rxbuff.head] == ENDBYTE)) 							// check header
				{
					 checksum=checksum(Rxbuff.data,  received_byte);
					 if (checksum == Rxbuff.data[Rxbuff.head-1])		// valid Data
					 {
						 StateMachine = ST_Parse;
					 }
					 else
					 {
						 	 	 	 	 	 	 	 	 	 	 	 	// Not valid data, parse upto next start of frame by incrementing tail
					 }
				}
			}
			break;
		}
		case ST_Parse:
		{
			uint8_t i;
			for (i = Rxbuff.tail; i< Rxbuff.head; i++)
			{
				SensorData.payload[i] = Rxbuff.data[Rxbuff.tail + i];		// copy main DATA
			}

			break;
		}
	}

}



uint8_t CheckSum(const uint8_t *buffer, uint8_t size)
{
	uint8_t i=0;
	uint8_t checksum =0 ;
	for (i=0; i<size; i++)
	{
		checksum = buffer[i] ^ checksum;
	}
	return checksum;
}


